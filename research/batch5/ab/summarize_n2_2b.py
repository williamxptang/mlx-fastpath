"""Table for the 2B N2 rows (ab_n2_2b.jsonl + kl_n2_2b.jsonl, one ABBA session): speed vs OptiQ stock of the same
session, QA, code edit, first split vs OptiQ stock, 4-gram uniqueness; KL vs bf16 next to the A/B's OptiQ / int4 rows.
Writes results_n2_2b.md."""
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
rows = [json.loads(l) for l in open(HERE / "ab_n2_2b.jsonl")]
by = defaultdict(list)
for r in rows:
    by[(r["weights"], r["runtime"], r["prompt"])].append(r)
P = ["chat", "math", "code_edit", "needle_4k"]
med = lambda w, rt, p: st.median(r["e2e_tok_s"] for r in by[(w, rt, p)])
cfgs = [("optiq", "stock"), ("optiq", "fast-ar"), ("optiq", "fast-mtp"), ("optiq-n2", "fast-ar"), ("optiq-n2", "fast-mtp")]
out = ["# Qwen3.5-2B: N2 vs OptiQ (one ABBA session; generated by summarize_n2_2b.py)", "",
       "e2e tok/s, median of 2 runs; x = vs OptiQ stock in this session.", "",
       "| weights | runtime | " + " | ".join(P) + " | QA (each run) |", "|" + "---|" * (len(P) + 3)]
for w, rt in cfgs:
    cells = [f"{med(w, rt, p):.0f} ({med(w, rt, p) / med('optiq', 'stock', p):.2f}x)" for p in P]
    out.append(f"| {w} | {rt} | " + " | ".join(cells) + f" | {', '.join(str(r['score']) for r in by[(w, rt, 'qa')])} |")
out += ["", "| weights | runtime | code edit (compiles/MODULES/MAX_VERIFY) | first split vs OptiQ stock "
        "(chat/math/code/needle; 300 = identical) | uniq4 chat |", "|---|---|---|---|---|"]
r0 = lambda w, rt, p: next(r for r in by[(w, rt, p)] if r["rep"] == 0)


def split(a, b):
    return next((k for k, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))


for w, rt in cfgs:
    ce = r0(w, rt, "code_edit")["score"]
    sp = "/".join(str(split(r0("optiq", "stock", p)["ids"], r0(w, rt, p)["ids"])) for p in P)
    out.append(f"| {w} | {rt} | {ce['compiles']}/{ce['edit_modules']}/{ce['edit_max_verify']} | {sp} | "
               f"{r0(w, rt, 'chat')['unique_4gram']} |")
kl = [json.loads(l) for l in open(HERE / "kl.jsonl")] + [json.loads(l) for l in open(HERE / "kl_n2_2b.jsonl")]
out += ["", "KL vs bf16 (same reference, text and tokens as the A/B):", "", "| weights | KL mean | KL p99 | top-1 |",
        "|---|---|---|---|"]
out += [f"| {r['weights']} | {r['kl_mean']} | {r['kl_p99']} | {r['top1']:.3f} |" for r in kl if r["model"] == "q2b"]
(HERE / "results_n2_2b.md").write_text("\n".join(out) + "\n")
print("\n".join(out))

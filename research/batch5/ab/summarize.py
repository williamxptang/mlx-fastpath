"""Tables from ab.jsonl (+ kl.jsonl): speed per model x weights x runtime (median of the ABBA repeats), speed-up vs
stock on the same weights and vs bf16 stock, and output quality: QA score, needle codes, math, code edit, first split vs
stock on the same weights, 4-gram uniqueness. Writes results.md next to it."""
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
rows = [json.loads(l) for l in open(HERE / "ab.jsonl")]
kl = [json.loads(l) for l in open(HERE / "kl.jsonl")] if (HERE / "kl.jsonl").exists() else []
SPEED = ["chat", "math", "code_edit", "needle_4k"]
by = defaultdict(list)
for r in rows:
    by[(r["model"], r["weights"], r["runtime"], r["prompt"])].append(r)


def med(key, model, w, rt, prompt):
    v = [r[key] for r in by.get((model, w, rt, prompt), []) if r.get(key) is not None]
    return st.median(v) if v else None


def split(a, b):
    return next((k for k, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))


configs = sorted({(r["model"], r["weights"], r["runtime"]) for r in rows},
                 key=lambda c: (["q08", "q2b", "gemma"].index(c[0]), ["bf16", "int4", "optiq", "optiq-n2"].index(c[1]),
                                ["stock", "optiq-mtp", "fast-ar", "fast-mtp", "fast-ngram"].index(c[2])))
out = ["# A/B results (generated by summarize.py from ab.jsonl)", "",
       "Speed = end-to-end tok/s (new tokens / wall time incl. prefill), median over the ABBA repeats. "
       "x = vs stock (mlx-lm) on the same weights; xbf16 = vs bf16 stock of the same model.", ""]
for model in ["q08", "q2b", "gemma"]:
    cs = [c for c in configs if c[0] == model]
    if not cs:
        continue
    out += [f"## {model}", "", "| weights | runtime | " + " | ".join(f"{p} tok/s (x, xbf16)" for p in SPEED)
            + " | QA (of 12, each run) | runs |", "|" + "---|" * (len(SPEED) + 4)]
    for m, w, rt in cs:
        cells = []
        for p in SPEED:
            v = med("e2e_tok_s", m, w, rt, p)
            base = med("e2e_tok_s", m, "optiq" if w == "optiq-n2" else w, "stock", p)
            b16 = med("e2e_tok_s", m, "bf16", "stock", p)
            cells.append("—" if v is None else f"{v:.0f} ({v / base:.2f}x, {v / b16:.2f}x)" if base and b16
                         else f"{v:.0f}")
        qa = [r["score"] for r in by.get((m, w, rt, "qa"), [])]
        runs = len(by.get((m, w, rt, "chat"), []))
        out.append(f"| {w} | {rt} | " + " | ".join(cells) + f" | {', '.join(map(str, qa)) or '—'} | {runs} |")
    out += ["", "Output vs stock on the same weights (rep 0): needle codes /3, math boxed, code edit "
            "(compiles/MODULES edit/MAX_VERIFY edit), first split position vs stock (300 = identical), 4-gram uniqueness "
            "(chat).", "", "| weights | runtime | needle | math | code edit | split chat/math/code/needle | uniq4 chat |",
            "|---|---|---|---|---|---|---|"]
    for m, w, rt in cs:
        r0 = {p: next((r for r in by.get((m, w, rt, p), []) if r["rep"] == 0), None) for p in SPEED}
        s0 = {p: next((r for r in by.get((m, "optiq" if w == "optiq-n2" else w, "stock", p), []) if r["rep"] == 0), None)
              for p in SPEED}
        sp = "/".join(str(split(s0[p]["ids"], r0[p]["ids"])) if r0[p] and s0[p] else "?" for p in SPEED)
        ce = r0["code_edit"]["score"] if r0["code_edit"] else None
        ce = "/".join(str(ce[k]) for k in ("compiles", "edit_modules", "edit_max_verify")) if ce else "?"
        out.append(f"| {w} | {rt} | {r0['needle_4k']['score'] if r0['needle_4k'] else '?'} | "
                   f"{r0['math']['score'] if r0['math'] else '?'} | {ce} | {sp} | "
                   f"{r0['chat']['unique_4gram'] if r0['chat'] else '?'} |")
    out.append("")
if kl:
    out += ["## Weights quality vs bf16 (teacher-forced, 1024 tokens of research/batch4/plan.md)", "",
            "| model | weights | KL mean | KL p99 | top-1 agreement |", "|---|---|---|---|---|"]
    out += [f"| {r['model']} | {r['weights']} | {r['kl_mean']} | {r['kl_p99']} | {r['top1']:.3f} |" for r in kl]
(HERE / "results.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
